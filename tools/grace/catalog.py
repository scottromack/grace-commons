"""tools/grace/catalog.py — the catalog: one generated entry per atom and per app, read first.

Unit `tooling: the catalog` (Scott 2026-11-25 5:26 PM Central, "yes!", on his idea of 5:25 PM:
"Grace trained AI can know where all is and only pull when needed"). A database's catalog: an AI
loads library/catalog.md whole, and pulls an atom's page only when it needs the rules.

Each atom's entry: its name, the first sentence of its What it is, the ids it mints (the keys of
its key offers: Bonds Key 14, an atom offers no id it does not mint), its needs and its offers by
bond kind and declared word, and its line count. Each app's entry: its atoms and its bond
instances (a need of the app's atoms or the app's page met by an offer of the app's atoms, as
bonds.md Bond 10 reads them). Everything is read from the bond lines check.py parses; nothing is
written by hand.

It also draws the bond graph (atoms as nodes, a need meeting an offer as an edge labelled by its
declared word), which tools/taxonomy/generate_graph.py places at the head of library/graph.md.

generate_graph.py writes the catalog on every run, so whoever regenerates the views regenerates
it, and the linter's V-views-current reports a stale catalog as it reports a stale graph.

Usage:  python3 tools/grace/catalog.py [repo-root]     # writes <root>/library/catalog.md
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check  # noqa: E402

LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")
SENTENCE = re.compile(r"(.+?[.!?][*_\"'”)]*)(?=\s+[A-Z(\[*_`]|\s*$)", re.S)


def title_of(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    fm = check._FRONT_MATTER.match(text)
    t = re.search(r"^title:[ \t]*(.+)$", fm.group(1), re.M) if fm else None
    return t.group(1).strip().strip('"') if t else path.stem.replace("-", " ").title()


def first_sentence(text: str) -> str:
    """The first sentence of the page's What it is (its Summary, on a page the converter has not yet rewritten),
    its links read as their text."""
    m = re.search(r"^## (?:What it is|Summary)\s*\n\s*(.*?)(?=^\s*$|^<details|^## )", text, re.S | re.M)
    if not m:
        return ""
    para = re.sub(r"\s+", " ", LINK.sub(r"\1", m.group(1))).strip()
    s = SENTENCE.match(para)
    return (s.group(1) if s else para).strip()


def word(b: dict) -> str:
    """The declared word a bond line is typed by: its key, the records it journals, or the subject it gates."""
    for f in ("key", "records", "subject"):
        v = b["fields"].get(f)
        if v:
            return v if isinstance(v, str) else ", ".join(sorted(v))
    return ""


def shown(b: dict) -> str:
    w = word(b)
    return f"{b['kind']} {w}" if w else b["kind"]


def corpus(root: Path) -> dict:
    """The atoms and apps with their bond lines, and every need met by an offer, as check.py reads them."""
    kinds = check.bond_kinds(root)
    words, types = check.declared_words(root)
    atoms = [p for p in check.pattern_files(root) if p.parent.name == "atoms"]
    apps = sorted((root / "library" / "apps").glob("*/index.md"))
    lines = {p: check.bond_lines(p, kinds) for p in atoms + apps}
    offers = [b for p in atoms for b in lines[p] if b["side"] == "offer"]
    meets = {}
    for p in atoms + apps:
        for need in (b for b in lines[p] if b["side"] == "need"):
            meets[(p, need["line"])] = [o for o in offers if check.bond_meets(need, o, words, types)]
    return {"atoms": atoms, "apps": apps, "lines": lines, "meets": meets,
            "titles": {p: title_of(p) for p in atoms + apps}}


def catalog(root: Path, data: dict | None = None) -> str:
    d = data or corpus(root)
    titles = d["titles"]
    L = ["---", "title: Catalog", "nav_order: 8", "---", "",
         "<!-- GENERATED by tools/grace/catalog.py — do not hand-edit; regenerate with",
         "     `python3 tools/grace/catalog.py .` (tools/taxonomy/generate_graph.py runs it too). -->", "",
         "# Catalog", "",
         "Every atom and app in one page, small enough to keep loaded whole: what each one is, the ids it mints, "
         "and what it needs and offers, by bond kind and declared word ([Bonds](./bonds.md), "
         "[Declarations](./declarations.md)). Read this first; open a page only for its rules. "
         "The [bond graph](./graph.md) draws the same needs and offers.", ""]
    bonded = sum(1 for p in d["atoms"] if d["lines"][p])
    L += [f"{len(d['atoms'])} atoms, {bonded} with bond lines; {len(d['apps'])} app(s).", "", "## Atoms", ""]
    for p in d["atoms"]:
        text = p.read_text(encoding="utf-8")
        bl = d["lines"][p]
        mints = sorted({b["fields"]["key"] for b in bl if b["side"] == "offer" and b["kind"] == "key"
                        and isinstance(b["fields"].get("key"), str)})
        needs = [shown(b) for b in bl if b["side"] == "need"]
        offers = [shown(b) for b in bl if b["side"] == "offer"]
        L.append(f"**[{titles[p]}](./atoms/{p.name})** ({text.count(chr(10)) + 1} lines). {first_sentence(text)}")
        parts = []
        if mints:
            parts.append("mints " + ", ".join(mints))
        if needs:
            parts.append("needs " + "; ".join(needs))
        if offers:
            parts.append("offers " + "; ".join(offers))
        L += ["", ("- " + ". ".join(p[0].upper() + p[1:] for p in parts) + ".") if parts else "- No bond lines yet.", ""]
    L += ["## Apps", ""]
    for app in d["apps"]:
        names = set(check.APP_ATOM.findall(app.read_text(encoding="utf-8")))
        mine = [p for p in d["atoms"] if p.stem in names]
        L += [f"**[{titles[app]}](./apps/{app.parent.name}/index.md)**. Atoms: "
              + ", ".join(titles[p] for p in mine) + ".", ""]
        for p in mine + [app]:
            for need in (b for b in d["lines"][p] if b["side"] == "need"):
                met = [o for o in d["meets"][(p, need["line"])] if o["path"] in mine]
                to = ", ".join(titles[o["path"]] for o in met) or "no offer of the app's atoms"
                L.append(f"- {titles[p]} needs {shown(need)}: met by {to}.")
        L.append("")
    return "\n".join(L).rstrip("\n") + "\n"


HUB_SHARE = 6  # an offer met by the needs of one atom in six or more is drawn as a tag, not a node


def bond_layers(data: dict) -> dict:
    """The bond graph as the readable view draws it (unit `site: the bond graph made readable`): the hub
    offers, the opaque key needs, the real arrows left, and each atom's layer. A hub is an offer the needs of
    one atom in HUB_SHARE or more meet (Actor Identity's actor id, Event Log's journal); it is drawn as a tag
    in each needing atom's box. A key need typed opaque (Ordering's) meets every key offer and is drawn as no
    arrow. An atom's layer is its depth in the arrows left: an atom with none is layer 0."""
    d = data
    atoms = d["atoms"]
    met_by: dict = {}
    for p in atoms:
        for need in (b for b in d["lines"][p] if b["side"] == "need"):
            for o in d["meets"][(p, need["line"])]:
                met_by.setdefault((o["path"], o["line"]), set()).add(p)
    hubs = {k for k, v in met_by.items() if len(v) * HUB_SHARE >= len(atoms)}
    hub_word = {}
    for p in atoms:
        for o in (b for b in d["lines"][p] if b["side"] == "offer" and (p, b["line"]) in hubs):
            hub_word[(p, o["line"])] = word(o) if o["kind"] == "key" else o["kind"]
    tags = {p: [] for p in atoms}
    opaque = []
    arrows = {p: [] for p in atoms}
    for p in atoms:
        for need in (b for b in d["lines"][p] if b["side"] == "need"):
            if need["kind"] == "key" and word(need) == "opaque":
                opaque.append(p)
                continue
            for o in d["meets"][(p, need["line"])]:
                k = (o["path"], o["line"])
                if k in hubs:
                    if hub_word[k] not in tags[p]:
                        tags[p].append(hub_word[k])
                elif o["path"] != p:
                    arrows[p].append((o["path"], word(need) or need["kind"]))
    layer: dict = {}

    def depth(p, seen=()):
        if p not in layer:
            if p in seen:
                return 0
            layer[p] = 1 + max(depth(q, seen + (p,)) for q, _ in arrows[p]) if arrows[p] else 0
        return layer[p]

    for p in atoms:
        depth(p)
    # an atom drawn: one with an arrow left, out or in; an atom that needs nothing and that nothing needs (the
    # hub tags aside) stands alone and is not drawn (Scott 2026-11-26 11:28 AM Central: "Dont list 'stand alones'")
    needed = {q for p in atoms for q, _ in arrows[p]}
    drawn = [p for p in atoms if arrows[p] or p in needed]
    return {"hubs": sorted({(o, hub_word[(o, ln)]) for o, ln in hubs}, key=str), "tags": tags,
            "opaque": sorted(set(opaque)), "arrows": arrows, "layer": layer, "drawn": drawn,
            "alone": [p for p in atoms if p not in drawn]}


def bond_graph(root: Path, data: dict | None = None) -> list[str]:
    """The bond graph as Markdown lines for graph.md: the layers in one diagram, then one small diagram per
    layer with its atoms and their real arrows, each labelled by the need's declared word (bond_layers)."""
    d = data or corpus(root)
    titles = d["titles"]
    v = bond_layers(d)
    layer, arrows, tags = {p: v["layer"][p] for p in v["drawn"]}, v["arrows"], v["tags"]
    drawn = v["drawn"]
    stem = {p: re.sub(r"\W", "_", p.stem) for p in d["atoms"]}
    init = '%%{init: {"theme": "dark", "flowchart": {"htmlLabels": true}} }%%'
    hub_names = " and ".join(f"{titles[o]}'s {w}" for o, w in v["hubs"])
    L = ["## The bond graph", "",
         "The atoms that bond, grouped by layer: an arrow runs from an atom to each atom whose offer one of its "
         "needs meets ([Bonds](./bonds.md)), and an atom's layer is how deep its arrows go (layer 0 is the "
         "foundations, atoms other atoms need and that need none). An atom that needs nothing and that nothing "
         "needs is not drawn; the [Catalog](./catalog.md) lists every atom with its need and offer lines. Drawn "
         "from those lines by tools/grace/catalog.py. Compositions keep the composition graph below until they "
         "dissolve.", ""]
    top = sorted(set(layer.values()), reverse=True)
    L += ["```mermaid", init, "flowchart TB"]
    for k in top:
        n = sum(1 for p in layer if layer[p] == k)
        names = ", ".join(titles[p] for p in drawn if layer[p] == k) if n <= 6 else ""
        label = f"Layer {k}: {n} atom{'s' if n != 1 else ''}" + (f"<br/>{names}" if names else "")
        L.append(f'  layer{k}["{label}"]')
    between: dict = {}
    for p in drawn:
        for q, _ in arrows[p]:
            between[(layer[p], layer[q])] = between.get((layer[p], layer[q]), 0) + 1
    for (a, b), n in sorted(between.items(), reverse=True):
        L.append(f'  layer{a} -->|"{n} bond{"s" if n != 1 else ""}"| layer{b}')
    L += ["```", ""]

    for k in top:
        # each diagram names its nodes apart (b<layer>_<atom>): Mermaid draws every diagram of a page into one
        # document, so one id in two diagrams draws both into the first
        nid = {p: f"b{k}_{stem[p]}" for p in d["atoms"]}

        def box(p):
            t = titles[p] + (f"<br/><small>{' · '.join(tags[p])}</small>" if tags[p] else "")
            return f'  {nid[p]}["{t}"]'

        own = [p for p in drawn if layer[p] == k]
        L += [f"### Layer {k}", "", "```mermaid", init, "flowchart TB" if k == 0 else "flowchart LR"]
        L += [box(p) for p in own]
        if k == 0:
            # the foundations, each with its arrows up to the atoms that need it (drawn dashed, of a higher layer)
            above = sorted({p for p in drawn if any(q in own for q, _ in arrows[p])}, key=lambda p: titles[p])
            L += [box(p) for p in above]
            L += [f"  class {','.join(nid[p] for p in above)} lower"] if above else []
            L += [f'  {nid[p]} -->|"{w}"| {nid[q]}' for p in above for q, w in arrows[p] if q in own]
            L.append("  classDef lower stroke-dasharray: 4 4")
        else:
            below = sorted({q for p in own for q, _ in arrows[p]} - set(own), key=lambda q: titles[q])
            L += [box(q) for q in below]
            L += [f"  class {','.join(nid[q] for q in below)} lower"] if below else []
            L += [f'  {nid[p]} -->|"{w}"| {nid[q]}' for p in own for q, w in arrows[p]]
            L.append("  classDef lower stroke-dasharray: 4 4")
        L += ["```", ""]
        L += [f"Layer {k}: " + ", ".join(f"[{titles[p]}](./atoms/{p.name})" for p in own) + "."
              + (" A dashed box is an atom of a lower layer." if k else
                 " A dashed box is an atom of a higher layer that needs one of them."), ""]
    if v["hubs"]:
        L += [f"A tag in an atom's box names a need met by an offer so many atoms need that it is drawn as no "
              f"node and no arrows: {hub_names}. An app names the atom that meets it.", ""]
    if v["opaque"]:
        names = [titles[p] for p in v["opaque"]]
        who = names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
        L += [f"{who} {'holds' if len(names) == 1 else 'hold'} a key need typed opaque, which any atom that offers a key "
              "meets, so it is drawn as no arrows; an app names which atom's key (a bond instance).", ""]
    unmet = [f"{titles[p]} ({shown(n)})" for p in d["atoms"] for n in d["lines"][p]
             if n["side"] == "need" and not d["meets"][(p, n["line"])]]
    if unmet:
        L += ["Needs no atom's offer meets: " + "; ".join(unmet) + ".", ""]
    return L


